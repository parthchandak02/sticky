"""Generate src/font.h: Inter Bold at two sizes, ASCII 32..126, 1 bit per pixel.

The device only draws its own text for status messages (no Wi-Fi, no server, updating);
every real screen comes from the server. Run from the firmware folder:
    uv run --with pillow python scripts/make_font.py
"""

from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
TTF = ROOT.parent / "assets" / "fonts" / "Inter-700.ttf"
SIZES = {"big": 34, "small": 22}


def glyphs(size: int):
    font = ImageFont.truetype(str(TTF), size)
    ascent, descent = font.getmetrics()
    height = ascent + descent
    out = []
    for code in range(32, 127):
        ch = chr(code)
        adv = round(font.getlength(ch))
        w = max(1, adv)
        img = Image.new("L", (w, height), 0)
        ImageDraw.Draw(img).text((0, 0), ch, font=font, fill=255)
        bits = []
        for y in range(height):
            row = 0
            for x in range(w):
                if img.getpixel((x, y)) >= 110:
                    row |= 1 << x
            bits.append(row)
        out.append((w, adv, bits))
    return height, ascent, out


def main() -> None:
    lines = ["// Generated by scripts/make_font.py from Inter Bold. Do not edit.", "#pragma once", "#include <stdint.h>", ""]
    lines += ["struct FontGlyph { uint8_t w, adv; uint32_t offset; };",
              "struct Font { uint8_t height, ascent; const FontGlyph* glyphs; const uint8_t* data; };", ""]
    for name, size in SIZES.items():
        height, ascent, gl = glyphs(size)
        data, table = [], []
        for w, adv, bits in gl:
            table.append(f"{{{w},{adv},{len(data)}}}")
            row_bytes = (w + 7) // 8
            for row in bits:
                for b in range(row_bytes):
                    data.append((row >> (b * 8)) & 0xFF)
        lines.append(f"static const uint8_t FONT_{name.upper()}_DATA[] = {{")
        for i in range(0, len(data), 24):
            lines.append("  " + ",".join(str(v) for v in data[i:i + 24]) + ",")
        lines.append("};")
        lines.append(f"static const FontGlyph FONT_{name.upper()}_GLYPHS[] = {{{','.join(table)}}};")
        lines.append(f"static const Font FONT_{name.upper()} = {{{height}, {ascent}, FONT_{name.upper()}_GLYPHS, FONT_{name.upper()}_DATA}};")
        lines.append("")
    (ROOT / "src" / "font.h").write_text("\n".join(lines))
    print("wrote src/font.h")


if __name__ == "__main__":
    main()
